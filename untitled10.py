import pandas as pd
df=pd.read_csv("/content/vehicle_sales_dirty.csv")
df

df.duplicated()

df["Brand"]=df["Brand"].fillna(df["Brand"].mode()[0])

df["Brand"].unique()

df["Brand"]=df["Brand"].replace({"ford":"ford"})

df["Fuel_Type"]=df["Fuel_Type"].fillna(df["Fuel_Type"].mode()[0])

df["Transmission"]=df["Transmission"].fillna(df["Transmission"].mode() [0])

df["Transmission"].unique()

df["Transmission"]=df["Transmission"].replace({"auto":"Automatic", "manual":"Manual"})

df["Seller_Type"].unique()

df["Seller_Type"]=df["Seller_Type"].replace({"dealer":"Dealer", "individual":"Individual"})

df["Owner"]=df["Owner"].fillna(df["Owner"].mode()[0])

df["Owner"].unique()

df["Fuel_Type"]=df["Fuel_Type"].fillna(df["Fuel_Type"].mode()[0])

df["Owner"]=df["Owner"].replace({"First":"1st", "Second":"2nd", "Third": "3rd"})

df["Seller_Price"]=df["Selling_Price"]

df["Selling_Price"]=df["Selling_Price"].fillna(df["Selling_Price"].mean())

df["Brand_dup"]=df["Brand_dup"].fillna(df["Brand_dup"].mode()[0])

df["Brand_dup"].unique()

df["Brand_dup"]=df["Brand_dup"].replace({"ford":"Ford", "toyota":"Toyota"})

df["Selling_Price_dup"]=df["Selling_Price_dup"].fillna(df["Selling_Price_dup"].mode()[0])

df.info()

df.to_csv("preprocessed_data.csv",index=False)