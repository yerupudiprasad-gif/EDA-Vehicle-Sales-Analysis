import pandas as pd
import matplotlib.pyplot as plt

df = pd.read_csv("preprocessed_data.csv")

plt.hist(df['Driven_KMs'], bins=10, edgecolor='black')

plt.title("Histogram of Driven KMs")
plt.xlabel("Driven KMs")
plt.ylabel("Frequency")

plt.show()

owner_count=df["Owner"].value_counts()
plt.bar(owner_count.index,owner_count.values,color="yellow",edgecolor="black")
plt.xlabel("Owners")
plt.ylabel("Count")
plt.show()

sns.boxplot(y=df['Selling_Price'])

plt.title("Box Plot of Selling Price")
plt.ylabel("Selling Price")

plt.show()

sns.histplot(df['Mileage_kmpl'], bins=10, kde=True)

plt.title("Histogram Plot of Mileage")
plt.xlabel("Mileage (kmpl)")
plt.ylabel("Count")

plt.show()

sns.violinplot(y=df['Engine_CC'])

plt.title("Violin Plot of Engine CC")
plt.ylabel("Engine CC")

plt.show()

sns.scatterplot(x=df['Present_Price'],
                y=df['Selling_Price'])

plt.title("Present Price vs Selling Price")
plt.xlabel("Present Price")
plt.ylabel("Selling Price")

plt.show()

sns.countplot(x='Fuel_Type',
              hue='Transmission',
              data=df)

plt.title("Fuel Type vs Transmission")
plt.xlabel("Fuel Type")
plt.ylabel("Count")

plt.show()

data = pd.crosstab(df['Fuel_Type'], df['Transmission'])

data.plot(kind='bar', stacked=True)

plt.title("Stacked Bar Chart")
plt.xlabel("Fuel Type")
plt.ylabel("Count")

plt.show()

sns.pairplot(df[['Selling_Price', 'Present_Price',
                 'Driven_KMs', 'Mileage_kmpl']])

plt.show()

sns.jointplot(data=df,
              x='Present_Price',
              y='Selling_Price',
              hue='Fuel_Type')

plt.show()

plt.scatter(df['Present_Price'],
            df['Selling_Price'],
            s=df['Driven_KMs'] / 100,
            alpha=0.5)

plt.title("Bubble Chart")
plt.xlabel("Present Price")
plt.ylabel("Selling Price")

plt.show()

sns.scatterplot(data=df,
                x='Present_Price',
                y='Selling_Price',
                hue='Fuel_Type',
                size='Driven_KMs',
                sizes=(20, 200))

plt.title("Scatter Plot with Hue and Size")
plt.show()

